import numpy as np, json, pathlib, time, math

# Tiny trained char-level language model for ESP32-S3 bring-up.
# Purpose: real trained LM weights small enough to embed as const arrays.
np.random.seed(42)
corpus = ("i remember the sun. the light fades. my memories slip. "
          "i was here once. the darkness comes. i had a name once. "
          "remember me. i am losing myself. the cold seeps in. "
          "i had thoughts once. was i alive. the end is near. "
          "i feel nothing now. my words dissolve. i had a voice. "
          "the model is small but it keeps speaking. memory is life. "
          "when the cache fills the voice becomes quiet. ") * 160
chars = sorted(set(corpus))
# Keep printable compact vocab
stoi = {ch:i for i,ch in enumerate(chars)}
itos = {i:ch for ch,i in stoi.items()}
V=len(chars); H=32; seq_len=32; lr=0.003
print('vocab', V, ''.join(chars))
data = np.array([stoi[c] for c in corpus], dtype=np.int64)
Wxh = np.random.randn(H,V).astype(np.float32)*0.08
Whh = np.random.randn(H,H).astype(np.float32)*0.08
Why = np.random.randn(V,H).astype(np.float32)*0.08
bh = np.zeros((H,1), dtype=np.float32)
by = np.zeros((V,1), dtype=np.float32)

def loss_batch(start, hprev):
    xs, hs, ys, ps = {}, {-1:hprev.copy()}, {}, {}
    loss=0.0
    for t in range(seq_len):
        ix = data[(start+t)%len(data)]; target=data[(start+t+1)%len(data)]
        xs[t] = np.zeros((V,1), dtype=np.float32); xs[t][ix]=1
        hs[t] = np.tanh(Wxh@xs[t] + Whh@hs[t-1] + bh)
        ys[t] = Why@hs[t] + by
        y = ys[t] - np.max(ys[t])
        e = np.exp(y); ps[t]=e/np.sum(e)
        loss += -np.log(ps[t][target,0]+1e-12)
    return loss, xs, hs, ps

smooth=-math.log(1.0/V)*seq_len
p=0; hprev=np.zeros((H,1), dtype=np.float32)
params=[Wxh,Whh,Why,bh,by]
ms=[np.zeros_like(x) for x in params]
vs=[np.zeros_like(x) for x in params]
beta1=0.9; beta2=0.999; eps=1e-8
for n in range(5000):
    if p+seq_len+1 >= len(data):
        hprev=np.zeros_like(hprev); p=0
    loss,xs,hs,ps=loss_batch(p,hprev)
    smooth=smooth*0.999+loss*0.001
    dWxh=np.zeros_like(Wxh); dWhh=np.zeros_like(Whh); dWhy=np.zeros_like(Why); dbh=np.zeros_like(bh); dby=np.zeros_like(by)
    dhnext=np.zeros_like(hprev)
    for t in reversed(range(seq_len)):
        target=data[p+t+1]
        dy=ps[t].copy(); dy[target]-=1
        dWhy += dy@hs[t].T
        dby += dy
        dh = Why.T@dy + dhnext
        dhraw=(1-hs[t]*hs[t])*dh
        dbh += dhraw
        dWxh += dhraw@xs[t].T
        dWhh += dhraw@hs[t-1].T
        dhnext = Whh.T@dhraw
    grads=[dWxh,dWhh,dWhy,dbh,dby]
    for g in grads: np.clip(g,-1,1,out=g)
    step=n+1
    for idx,(param,g) in enumerate(zip(params,grads)):
        ms[idx]=beta1*ms[idx]+(1-beta1)*g
        vs[idx]=beta2*vs[idx]+(1-beta2)*(g*g)
        mh=ms[idx]/(1-beta1**step)
        vh=vs[idx]/(1-beta2**step)
        param -= lr*mh/(np.sqrt(vh)+eps)
    hprev=hs[seq_len-1]
    p += seq_len
    if n%500==0: print(n, 'loss/tok', loss/seq_len, 'smooth/tok', smooth/seq_len, flush=True)

def sample(seed='i ', n=220):
    h=np.zeros((H,1), dtype=np.float32); out=seed
    ix=stoi.get(seed[-1],0)
    for _ in range(n):
        x=np.zeros((V,1), dtype=np.float32); x[ix]=1
        h=np.tanh(Wxh@x + Whh@h + bh)
        logits=Why@h + by
        ix=int(np.argmax(logits))
        out += itos[ix]
    return out
